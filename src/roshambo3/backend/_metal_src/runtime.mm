// The native half of the experimental Apple Silicon Metal backend: a thin
// pybind11 module (_roshambo3_metal) that owns the device, buffers, textures
// and compiled pipelines, and runs batches of kernel launches described from
// Python. All scientific logic lives in kernels.metal and backend/metal.py;
// this file only moves bytes and encodes dispatches. See
// doc/METAL.md.
//
// Contract with metal.py:
//   * Context(index, source) compiles the whole shader source at runtime
//     (metal.py has already prepended its #defines and generated entry
//     points), with safe math and precise floating-point functions.
//   * Buffers use shared storage on a unified-memory device, so a write or
//     read is a plain memcpy; no staging copies, no CPU/GPU overlap.
//   * submit(jobs) encodes every job into ONE command buffer, commits it and
//     waits for completion before returning. Errors surface as Python
//     exceptions; nothing is left running when submit returns normally.
#import <Foundation/Foundation.h>
#import <Metal/Metal.h>
#include <pybind11/pybind11.h>
#include <pybind11/numpy.h>
#include <pybind11/stl.h>
#include <cstring>
#include <memory>
#include <stdexcept>
#include <unordered_map>
#include <vector>
// Source stamp generated by CMake from the _metal_src subtree, so a loaded
// binary can report which native source it was built from (metal.py
// `build_stamp`). Absent in builds without the stamp step.
#if __has_include("roshambo3_metal_stamp.h")
#include "roshambo3_metal_stamp.h"
#else
#define ROSHAMBO3_METAL_SRC_SHA256 "unknown"
#define ROSHAMBO3_METAL_SRC_DIRTY -1
#endif
namespace py = pybind11;

static std::string message(NSError* e) {
    return e ? std::string([[e localizedDescription] UTF8String])
             : "Metal operation failed";
}

// Device `index` of MTLCopyAllDevices, accepted only if it is an Apple GPU
// (family Apple1 or later) with unified memory, i.e. Apple Silicon. macOS 15
// or newer is the backend's documented requirement (doc/METAL.md); the
// compile options set in Context (mathMode, mathFloatingPointFunctions) are
// macOS 15 APIs.
static id<MTLDevice> device(int index) {
    if (@available(macOS 15.0, *)) {
        NSArray<id<MTLDevice>>* devices = MTLCopyAllDevices();
        if (index < 0 || index >= (int)devices.count)
            throw std::invalid_argument("Metal device index out of range");
        id<MTLDevice> d = devices[index];
        if (!d.hasUnifiedMemory || ![d supportsFamily:MTLGPUFamilyApple1])
            throw std::runtime_error(
                "Metal backend requires an Apple Silicon GPU");
        return d;
    }
    throw std::runtime_error("Metal backend requires macOS 15 or newer");
}

// One shared-storage MTLBuffer. write/read copy whole C-contiguous NumPy
// arrays in and out at the CPU-visible `contents` pointer, bounds-checked
// against the allocation. Callers order these copies against GPU work by
// only touching a buffer between submits.
struct Buffer {
    id<MTLBuffer> value;

    Buffer(id<MTLDevice> d, size_t n) {
        // At least 4 bytes, so an empty array still yields a bindable buffer.
        value = [d newBufferWithLength:std::max(size_t(4), n)
                               options:MTLResourceStorageModeShared];
        if (!value) throw std::bad_alloc();
    }

    void write(py::array a) {
        if (!(a.flags() & py::array::c_style))
            throw std::invalid_argument("buffer input must be C contiguous");
        if ((size_t)a.nbytes() > value.length)
            throw std::invalid_argument("buffer write exceeds allocation");
        std::memcpy(value.contents, a.data(), a.nbytes());
    }

    py::array read(py::dtype dtype, std::vector<py::ssize_t> shape,
                   size_t offset) {
        py::array a(dtype, shape);
        if (offset > value.length || (size_t)a.nbytes() > value.length - offset)
            throw std::invalid_argument("buffer read exceeds allocation");
        std::memcpy(a.mutable_data(), (char*)value.contents + offset,
                    a.nbytes());
        return a;
    }
};

// One 3D field texture: RGBA16Float (`half`) or RGBA32Float, holding the
// (value, gradient) nodes of a field. Private storage, because it is filled
// on the device by the pack_field kernel (hence ShaderWrite) and only ever
// sampled there. Filtering RGBA32Float requires Apple GPU family 9 (M3 or
// newer). 2048 per axis is the 3D texture limit relied on for the
// supported families.
struct Texture {
    id<MTLTexture> value;

    Texture(id<MTLDevice> d, size_t x, size_t y, size_t z, bool half) {
        if (!x || !y || !z || x > 2048 || y > 2048 || z > 2048)
            throw std::invalid_argument(
                "Metal 3D texture dimensions must be in [1,2048]");
        if (!half && ![d supportsFamily:MTLGPUFamilyApple9])
            throw std::invalid_argument(
                "RGBA32Float filtering requires Apple GPU family 9 or newer");
        MTLTextureDescriptor* desc = [MTLTextureDescriptor new];
        desc.textureType = MTLTextureType3D;
        desc.pixelFormat =
            half ? MTLPixelFormatRGBA16Float : MTLPixelFormatRGBA32Float;
        desc.width = x;
        desc.height = y;
        desc.depth = z;
        desc.storageMode = MTLStorageModePrivate;
        desc.usage = MTLTextureUsageShaderRead | MTLTextureUsageShaderWrite;
        value = [d newTextureWithDescriptor:desc];
        if (!value) throw std::bad_alloc();
    }
};

// One device context: command queue, compiled library, a lazily filled
// pipeline cache keyed by kernel name, and GPU timing counters. metal.py
// serializes use of a Context with its own lock.
struct Context {
    id<MTLDevice> dev;
    id<MTLCommandQueue> queue;
    id<MTLLibrary> library;
    std::unordered_map<std::string, id<MTLComputePipelineState>> pipelines;
    double gpu_seconds = 0;
    bool profile_kernels = false;
    std::unordered_map<std::string, double> kernel_seconds;

    Context(int index, std::string source) : dev(device(index)) {
        @autoreleasepool {
            queue = [dev newCommandQueue];
            if (!queue)
                throw std::runtime_error(
                    "Metal command queue allocation failed");
            // The numerical contract (doc/METAL.md): Metal 3.1, safe math (no
            // fast-math reassociation), and precise floating-point functions,
            // so the kernels' unqualified exp2/sin/cos/sqrt are the precise
            // ones. The optimizer's fast exp2 is opted into by name in the
            // shader (search_exp2), never by a compiler mode.
            MTLCompileOptions* options = [MTLCompileOptions new];
            options.languageVersion = MTLLanguageVersion3_1;
            if (@available(macOS 15.0, *)) {
                options.mathMode = MTLMathModeSafe;
                options.mathFloatingPointFunctions =
                    MTLMathFloatingPointFunctionsPrecise;
            }
            NSError* error = nil;
            library = [dev
                newLibraryWithSource:[NSString
                                         stringWithUTF8String:source.c_str()]
                             options:options
                               error:&error];
            if (!library) throw std::runtime_error(message(error));
        }
    }

    // Refuse an allocation that would exceed the per-buffer limit or push the
    // device past its recommended working set; metal.py sizes launches
    // against the same budget.
    std::shared_ptr<Buffer> allocate(size_t size) {
        if (size > dev.maxBufferLength ||
            dev.currentAllocatedSize + size > dev.recommendedMaxWorkingSetSize)
            throw std::runtime_error(
                "Metal working-set budget exceeded; reduce launch size, query count, or K");
        return std::make_shared<Buffer>(dev, size);
    }

    std::shared_ptr<Texture> texture(size_t x, size_t y, size_t z, bool half) {
        // Dimensions are bounded before multiplying, and allocation is charged
        // against the same device working set as buffers.
        if (!x || !y || !z || x > 2048 || y > 2048 || z > 2048)
            throw std::invalid_argument(
                "Metal 3D texture dimensions must be in [1,2048]");
        const size_t bytes = x * y * z * (half ? 8 : 16);
        if (bytes > dev.recommendedMaxWorkingSetSize ||
            dev.currentAllocatedSize > dev.recommendedMaxWorkingSetSize - bytes)
            throw std::runtime_error(
                "Metal texture working-set budget exceeded");
        return std::make_shared<Texture>(dev, x, y, z, half);
    }

    // Run a batch of kernel launches. Each job is a tuple
    //   (kernel name, [Buffer...], constants ndarray, thread count,
    //    threadgroup width[, [Texture...]])
    // Buffers bind at indices 0..n-1 in order, the constants (setBytes) at
    // index n, so every kernel's `constant` argument must follow its last
    // buffer; textures bind from texture index 0. Threads are dispatched
    // 1-D, one per element of `count`.
    void submit(py::list jobs) {
        // Diagnostic mode deliberately submits one command per kernel. These
        // timestamps attribute cost, but must not be used as normal API timings.
        if (profile_kernels) {
            profile_kernels = false;
            try {
                for (auto item : jobs) {
                    py::list one;
                    one.append(item);
                    double before = gpu_seconds;
                    submit(one);
                    kernel_seconds[py::cast<std::string>(
                        py::cast<py::tuple>(item)[0])] += gpu_seconds - before;
                }
            } catch (...) {
                profile_kernels = true;
                throw;
            }
            profile_kernels = true;
            return;
        }
        // Normal mode: one command buffer, one compute encoder per job, in
        // job order. A later job reads what an earlier one wrote (e.g.
        // build_field before pack_field before the optimizer).
        @autoreleasepool {
            id<MTLCommandBuffer> command = [queue commandBuffer];
            if (!command)
                throw std::runtime_error(
                    "Metal command buffer allocation failed");
            for (auto item : jobs) {
                py::tuple job = py::cast<py::tuple>(item);
                std::string name = py::cast<std::string>(job[0]);
                // Pipelines are compiled on first use and cached by name, so
                // a cold call's wall time can include pipeline compilation.
                auto found = pipelines.find(name);
                id<MTLComputePipelineState> pipeline;
                if (found == pipelines.end()) {
                    NSError* error = nil;
                    id<MTLFunction> fn = [library
                        newFunctionWithName:
                            [NSString stringWithUTF8String:name.c_str()]];
                    if (!fn)
                        throw std::runtime_error("Missing Metal kernel: " +
                                                 name);
                    pipeline = [dev newComputePipelineStateWithFunction:fn
                                                                  error:&error];
                    if (!pipeline) throw std::runtime_error(message(error));
                    pipelines.emplace(name, pipeline);
                } else
                    pipeline = found->second;
                size_t count = py::cast<size_t>(job[3]);
                size_t group = py::cast<size_t>(job[4]);
                if (!count) continue;
                // A threadgroup must be a whole number of SIMD groups. As the
                // SIMD width is a multiple of 4, the aligned four-thread quads
                // kernels.metal reduces with simd_shuffle_xor never straddle
                // one.
                if (!group || group > pipeline.maxTotalThreadsPerThreadgroup ||
                    group % pipeline.threadExecutionWidth)
                    throw std::invalid_argument(
                        "Invalid Metal threadgroup width");
                // Convert every Python-side argument BEFORE opening the
                // encoder. py::cast throws on a malformed job, and an
                // exception between computeCommandEncoder and endEncoding
                // would release the command buffer with an encoder still
                // open, which Metal treats as a contract violation (an
                // assertion under API validation). Nothing below the
                // encoder's creation can throw. The Buffer and Texture
                // objects stay alive through `jobs`, which the caller holds.
                std::vector<id<MTLBuffer>> buffers;
                for (auto b : py::cast<py::list>(job[1]))
                    buffers.push_back(
                        py::cast<std::shared_ptr<Buffer>>(b)->value);
                std::vector<id<MTLTexture>> textures;
                if (job.size() > 5)
                    for (auto t : py::cast<py::list>(job[5]))
                        textures.push_back(
                            py::cast<std::shared_ptr<Texture>>(t)->value);
                py::array constants = py::cast<py::array>(job[2]);
                id<MTLComputeCommandEncoder> enc =
                    [command computeCommandEncoder];
                if (!enc)
                    throw std::runtime_error(
                        "Metal compute encoder allocation failed");
                [enc setComputePipelineState:pipeline];
                unsigned index = 0;
                for (id<MTLBuffer> buffer : buffers)
                    [enc setBuffer:buffer offset:0 atIndex:index++];
                unsigned texture_index = 0;
                for (id<MTLTexture> texture : textures)
                    [enc setTexture:texture atIndex:texture_index++];
                if (constants.nbytes())
                    [enc setBytes:constants.data()
                           length:constants.nbytes()
                          atIndex:index];
                // Non-uniform dispatch: exactly `count` threads; the last
                // threadgroup may be partial, and kernels bound-check tid.
                [enc dispatchThreads:MTLSizeMake(count, 1, 1)
                    threadsPerThreadgroup:MTLSizeMake(group, 1, 1)];
                [enc endEncoding];
            }
            // Blocking wait with the GIL released, so other Python threads
            // run meanwhile. An execution error is raised here, and only
            // completed command buffers add to gpu_seconds.
            {
                py::gil_scoped_release release;
                [command commit];
                [command waitUntilCompleted];
            }
            if (command.status == MTLCommandBufferStatusError)
                throw std::runtime_error(message(command.error));
            gpu_seconds += command.GPUEndTime - command.GPUStartTime;
        }
    }
};

// Module surface: device_info for discovery (metal.available() and the
// texture32 capability check), Buffer/Texture handles, Context, and the build
// stamp attributes read by metal.build_stamp().
PYBIND11_MODULE(_roshambo3_metal, m) {
    m.def(
        "device_info",
        [](int index) {
            @autoreleasepool {
                auto d = device(index);
                py::dict out;
                out["name"] = std::string([d.name UTF8String]);
                out["registry_id"] = d.registryID;
                out["recommended_working_set_bytes"] =
                    d.recommendedMaxWorkingSetSize;
                out["max_buffer_bytes"] = d.maxBufferLength;
                out["unified_memory"] = bool(d.hasUnifiedMemory);
                out["float32_filtering"] =
                    bool([d supportsFamily:MTLGPUFamilyApple9]);
                return out;
            }
        },
        py::arg("device_id") = 0);
    py::class_<Buffer, std::shared_ptr<Buffer>>(m, "Buffer")
        .def("write", &Buffer::write)
        .def("read", &Buffer::read, py::arg("dtype"), py::arg("shape"),
             py::arg("offset") = 0);
    py::class_<Texture, std::shared_ptr<Texture>>(m, "Texture");
    py::class_<Context>(m, "Context")
        .def(py::init<int, std::string>())
        .def("allocate", &Context::allocate)
        .def("submit", &Context::submit)
        .def("texture", &Context::texture)
        .def_readwrite("gpu_seconds", &Context::gpu_seconds)
        .def_readwrite("profile_kernels", &Context::profile_kernels)
        .def_readwrite("kernel_seconds", &Context::kernel_seconds);
    m.attr("__metal_src_sha256__") = ROSHAMBO3_METAL_SRC_SHA256;
    m.attr("__metal_src_dirty__") = ROSHAMBO3_METAL_SRC_DIRTY;
    m.attr("__sdk_max_allowed__") = __MAC_OS_X_VERSION_MAX_ALLOWED;
    m.attr("__compiler__") = __clang_version__;
    m.attr("__build_type__") = ROSHAMBO3_METAL_BUILD_TYPE;
}
