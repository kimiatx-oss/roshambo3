#!/usr/bin/env python3
"""What source is this? One answer, used by the build stamp and the registry.

**The question this module exists to answer is not "which commit".** A commit
names an index, and every A/B arm this project measures is built from a tree
that departs from its index: patch scripts, a bisect, a control arm with one
file restored into a worktree. Such a binary stamps a commit whose code it does
not contain, and nothing in a run record from it can say so.

So the durable identity of a build's source is a **sha256 over the bytes of
every file about to be compiled**, which is dirty-aware by construction rather
than by anyone remembering to check. The binary reuse registry keys on the
same thing; this module is that function, lifted to where
both the registry and CMake can call it, because two implementations of "which
source is this" is exactly the drift to avoid.

The commit, the subtree tree-hash and the porcelain-dirty marker are recorded
*beside* the content hash as provenance, never as the identity:

* ``git rev-parse HEAD`` -- what the tree was branched from. Kept unchanged;
  archived run records key on ``ROSHAMBO3_GIT_SHA``.
* ``git rev-parse HEAD:<subtree>`` -- git's own content hash of the compiled
  subtree, the key the baseline and accuracy harnesses settled on. It still describes the index, so an uncommitted edit leaves it
  unchanged; that is why the dirty marker below is not optional.
* ``git status --porcelain -- <subtree>`` -- non-empty means the working tree
  matches no commit at all.

Invoked three ways:

* ``--header <path>`` -- write the C header CMake compiles into the extension.
  Rewritten only when its content changes, so a build that did not touch the
  source does not recompile ``interface.cpp``.
* ``--json`` -- the same facts, for a harness or a test.
* no argument -- a human-readable dump.

**It never fails a build.** Every recoverable problem (no git, no repository,
an unreadable file) yields ``"unknown"`` and exit 0, on the rule that a
bookkeeping step must not be able to stop a compile. What it must not do is
report *clean* when it did not look -- ``dirty`` is a tri-state for that reason:
1 dirty, 0 clean, -1 not established.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

CUDA_SRC_RELATIVE = "src/roshambo3/backend/_cuda_src"
"""The compiled subtree. `src` is the weaker key: a pure-Python change moves it
while the kernel is bit-identical."""

CPU_SRC_RELATIVE = "src/roshambo3/backend/_cpu_src"
"""The scalar CPU kernel's subtree.

That kernel is the **reference anchor** (``roshambo3.reference.anchor``): the third implementation both
optimized paths are compared against, precisely because a CPU score depends on
vector width and a GPU score on architecture, so neither can be the other's
reference. An anchor whose identity is a commit rather than its content is not
an anchor -- the same argument that produced the CUDA hash, and it binds
harder here, because a fixture generated by the anchor is only interpretable if
it can name the exact source that produced it.

Stamped through THIS module and not a second one: the header comment in
`CMakeLists.txt` says two implementations of "which source is this" is the drift
to avoid, and that applies to a second *subtree* as much as to a
second copy of the function."""

DIRTY_UNKNOWN = -1
DIRTY_CLEAN = 0
DIRTY_YES = 1

MAX_DIRTY_FILES = 20
"""How many porcelain paths the stamp carries. A cap, not a summary: the count
is reported in full, and this bounds a string compiled into a binary."""


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def source_content_hash(root: Path) -> str:
    """sha256 over the bytes of every file under ``root``.

    Path-then-hash, NUL-separated, in sorted order, so a rename moves it and two
    trees with the same files in different directories do not collide. This is
    the exact algorithm the binary reuse registry keys on -- that module now
    calls this one, so the key a build was stored under and the hash compiled into that build are the same number by
    construction, and a test can assert it.
    """
    h = hashlib.sha256()
    for f in sorted(root.rglob("*")):
        if not f.is_file():
            continue
        h.update(f.relative_to(root).as_posix().encode())
        h.update(b"\0")
        h.update(_sha256_file(f).encode())
        h.update(b"\0")
    return h.hexdigest()


def _git(repo: Path, *args: str) -> tuple[int, str]:
    """Returns (returncode, stdout) with stdout UNSTRIPPED.

    `git status --porcelain` puts two status columns before every path, and the
    first line's leading space is significant: stripping the whole output shifts
    exactly the first path by one character, which is a bug that reads as a
    corrupt file name in the one field a reader consults when the stamp says
    dirty. Callers strip what they mean to strip.
    """
    try:
        p = subprocess.run(["git", "-C", str(repo), *args],
                           capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return 1, ""
    return p.returncode, p.stdout


def git_provenance(repo: Path, subtree: str = CUDA_SRC_RELATIVE,
                   prefix: str = "cuda") -> dict:
    """The commit, the subtree tree-hash, and whether the subtree is dirty.

    Recorded beside the content hash, never as the identity. ``dirty`` is
    tri-state: a repository we could not interrogate reports
    :data:`DIRTY_UNKNOWN`, because "nobody looked" reaching a record as "clean"
    is a defect shape that has had to be fixed more than once.
    """
    rc_root, git_root = _git(repo, "rev-parse", "--show-toplevel")
    if rc_root != 0 or Path(git_root.strip()).resolve() != repo.resolve():
        return {
            "git_sha": "unknown", f"{prefix}_src_tree": "unknown",
            f"{prefix}_src_dirty": DIRTY_UNKNOWN,
            f"{prefix}_src_dirty_files": [], f"{prefix}_src_dirty_file_count": 0,
        }
    rc_sha, sha = _git(repo, "rev-parse", "HEAD")
    sha = sha.strip()
    rc_tree, tree = _git(repo, "rev-parse", f"HEAD:{subtree}")
    tree = tree.strip()
    rc_status, status = _git(repo, "status", "--porcelain", "--", subtree)
    if rc_status != 0:
        dirty, files = DIRTY_UNKNOWN, []
    else:
        # Two status columns, then the path. A rename reports "old -> new",
        # which is reported as it stands rather than parsed -- this field is
        # read by a human asking which file moved.
        files = [ln[2:].strip() for ln in status.splitlines() if ln.strip()]
        dirty = DIRTY_YES if files else DIRTY_CLEAN
    return {
        "git_sha": sha if rc_sha == 0 and sha else "unknown",
        f"{prefix}_src_tree": tree if rc_tree == 0 and tree else "unknown",
        f"{prefix}_src_dirty": dirty,
        f"{prefix}_src_dirty_files": files[:MAX_DIRTY_FILES],
        f"{prefix}_src_dirty_file_count": len(files),
    }


def stamp(repo: Path = REPO, subtree: str = CUDA_SRC_RELATIVE,
          phase: str = "unknown", prefix: str = "cuda") -> dict:
    """Everything the build stamp records about which source was compiled.

    ``prefix`` names the key family (``cuda_src_sha256``, ``cpu_src_sha256``).
    It defaults to ``cuda`` so every existing caller, header macro and archived
    run record keeps the exact keys it already has -- the second
    subtree was added by parameterizing this function rather than copying it.
    """
    root = repo / subtree
    try:
        content = source_content_hash(root) if root.is_dir() else "unknown"
    except OSError:
        content = "unknown"
    out = {f"{prefix}_src_sha256": content, "source_stamp_phase": phase}
    out.update(git_provenance(repo, subtree, prefix))
    return out


def _c_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def header_text(s: dict, prefix: str = "cuda") -> str:
    up = prefix.upper()
    files = ",".join(s[f"{prefix}_src_dirty_files"])
    return "\n".join([
        "/* Generated by scripts/source_stamp.py. Do not edit; do not commit.",
        " *",
        " * The build stamp's answer to 'which source was compiled', as opposed",
        " * to ROSHAMBO3_GIT_SHA's answer to 'which commit was checked out'.",
        " * The two disagree exactly when it matters most. */",
        "#pragma once",
        f"#define ROSHAMBO3_{up}_SRC_SHA256 {_c_string(s[f'{prefix}_src_sha256'])}",
        f"#define ROSHAMBO3_{up}_SRC_TREE {_c_string(s[f'{prefix}_src_tree'])}",
        f"#define ROSHAMBO3_{up}_SRC_DIRTY {int(s[f'{prefix}_src_dirty'])}",
        f"#define ROSHAMBO3_{up}_SRC_DIRTY_FILES {_c_string(files)}",
        f"#define ROSHAMBO3_SOURCE_STAMP_PHASE {_c_string(s['source_stamp_phase'])}",
        "",
    ])


def write_header(path: Path, s: dict, prefix: str = "cuda") -> bool:
    """Write the header only if it would change. Returns True if it did.

    An unconditional write would touch the mtime on every build, and every build
    would then recompile and relink the extension for a stamp that did not move.
    """
    text = header_text(s, prefix)
    try:
        if path.exists() and path.read_text() == text:
            return False
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    except OSError as e:                                    # noqa: BLE001
        print(f"source_stamp: could not write {path}: {e}", file=sys.stderr)
        return False
    return True


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo", default=str(REPO))
    ap.add_argument("--subtree", default=CUDA_SRC_RELATIVE)
    ap.add_argument("--prefix", default="cuda",
                    help="key/macro family: 'cuda' or 'cpu' (the reference anchor)")
    ap.add_argument("--phase", default="unknown",
                    help="when this stamp was taken: 'configure' or 'build'")
    ap.add_argument("--header", help="write the C header here")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv[1:])

    s = stamp(Path(args.repo), args.subtree, args.phase, args.prefix)
    if args.header:
        changed = write_header(Path(args.header), s, args.prefix)
        # Named on stdout so a build log says which source it stamped, and so a
        # no-op regeneration is visibly a no-op rather than silence.
        print(f"source_stamp[{args.phase}:{args.prefix}] "
              f"src={s[f'{args.prefix}_src_sha256'][:16]} "
              f"tree={s[f'{args.prefix}_src_tree'][:12]} "
              f"dirty={s[f'{args.prefix}_src_dirty']} "
              f"{'wrote' if changed else 'unchanged'} {args.header}")
    elif args.json:
        print(json.dumps(s, indent=2))
    else:
        print(json.dumps(s, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
